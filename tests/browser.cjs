// Run against tests/browser_server.py only; it blocks paid AI.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',headless:true,args:['--no-sandbox']});
 const base=process.env.TEST_BASE_URL||'http://127.0.0.1:18001';
 const errors=[];
 try {
  for(const role of ['qa','op','lead','adm']){
   const context=await browser.newContext({viewport:{width:1365,height:900}});
   const page=await context.newPage();
   page.on('pageerror',e=>errors.push(role+': '+e.message));
   await page.goto(base);
   await page.locator('#dr').waitFor();
   const options=await page.locator('#dr option').evaluateAll(xs=>xs.map(x=>({role:x.dataset.role,value:x.value})));
   assert.deepEqual(new Set(options.map(x=>x.role)),new Set(['qa','op','lead','adm']));
   await page.selectOption('#dr',options.find(x=>x.role===role).value);
   await page.click('#dgo');
   await page.locator('#nav').waitFor();
   const routes=await page.locator('#nav a').evaluateAll(xs=>xs.map(x=>x.getAttribute('href')));
   for(const route of routes){
    await page.goto(base+'/'+route);
    await page.locator('#view').waitFor();
    await page.waitForFunction(()=>!document.querySelector('#view .loading'));
    assert.ok(!(await page.locator('#crumbs').innerText()).includes('undefined'));
    assert.equal(await page.locator('#view > .note.bad').count(),0,role+' '+route+': '+await page.locator('#view').innerText());
   }
   await page.setViewportSize({width:390,height:844});
   await page.goto(base+'/#/'+({qa:'queue',op:'my',lead:'development',adm:'integrations'}[role]));
   await page.waitForFunction(()=>document.querySelector('#view')&&!document.querySelector('#view .loading'));
   await page.screenshot({path:'/tmp/freedom-'+role+'.png',fullPage:true});
   console.log('PASS browser role',role,routes.length,'routes, mobile render');
   await context.close();
  }
  const admin=await browser.newContext();
  const demo=await (await admin.request.get(base+'/api/auth/demo')).json();
  await admin.request.post(base+'/api/auth/demo/'+demo.users.find(u=>u.role==='adm').id);
  const users=await (await admin.request.get(base+'/api/users')).json();
  const lead=await browser.newContext();
  await lead.request.post(base+'/api/auth/demo/'+demo.users.find(u=>u.role==='lead').id);
  const dialogs=await (await lead.request.get(base+'/api/dialogs')).json();
  let d=dialogs.find(d=>['published','acknowledged','revised','appeal'].includes(d.wf_status));
  if(!d){
    d=dialogs.find(d=>d.wf_status==='review'&&d.eval_status==='done');
    assert.ok(d,'Need reviewable group dialog');
    const qa=await browser.newContext();
    await qa.request.post(base+'/api/auth/demo/'+demo.users.find(u=>u.role==='qa').id);
    const qp=await qa.newPage();
    await qp.goto(base+'/#/dialog/'+d.id);
    const confirmed=qp.waitForResponse(r=>r.url().endsWith('/confirm'));
    await qp.locator('[data-confirm]').click();
    assert.equal((await confirmed).status(),200);
    await qa.close();
  }
  assert.ok(d,'Need a published group dialog');
  const lp=await lead.newPage();lp.on('pageerror',e=>errors.push(e.message));
  await lp.goto(base+'/#/development');
  await lp.locator('#task-create').waitFor();
  await lp.locator('[name=dialog]').fill(d.id);
  await lp.locator('[name=instruction]').fill('Проверить критерий и подготовить разбор ошибки');
  const created=lp.waitForResponse(r=>r.url().endsWith('/api/development')&&r.request().method()==='POST');
  await lp.locator('#task-create button').click();
  const response=await created; assert.equal(response.status(),200);
  const tid=(await response.json()).id;
  const op=await browser.newContext();
  await op.request.post(base+'/api/auth/demo/'+users.find(u=>u.role==='op'&&u.name===d.operator).id);
  const page=await op.newPage();page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/#/development/'+tid);
  await page.locator('[data-task="'+tid+'"] textarea').fill('Разбор завершён, следующий ответ подготовлен');
  const submitted=page.waitForResponse(r=>r.url().endsWith('/submit'));
  await page.locator('[data-task="'+tid+'"] button').click();
  assert.equal((await submitted).status(),200);
  await lp.reload();
  await lp.locator('[data-task="'+tid+'"] textarea').fill('Проверено, результат соответствует задаче');
  const reviewed=lp.waitForResponse(r=>r.url().endsWith('/review'));
  await lp.locator('[data-task="'+tid+'"] button').click();
  assert.equal((await reviewed).status(),200);
  await page.reload();
  await page.getByRole('heading',{name:'Задача №'+tid+' · Выполнена'}).waitFor();
  console.log('PASS browser coaching: assign, submit, review, reload persistence');
  await page.goto(base+'/#/dialog/'+d.id);
  await page.locator('[data-sel="c1"]').waitFor();
  if(!await page.locator('[data-edit="c1"]').count()) await page.locator('[data-sel="c1"]').click();
  await page.locator('[data-edit="c1"]').click();
  await page.locator('[data-want="c1"]').first().click();
  await page.locator('#aptext').fill('Прошу проверить ответ оператора в реплике #1');
  const submittedAppeal=page.waitForResponse(r=>r.url().endsWith('/appeal')&&r.request().method()==='POST');
  await page.locator('[data-apsend]').click();
  const apResponse=await submittedAppeal;assert.equal(apResponse.status(),200);
  const aid=(await apResponse.json()).id;
  const qa=await browser.newContext();
  await qa.request.post(base+'/api/auth/demo/'+demo.users.find(u=>u.role==='qa').id);
  const qp=await qa.newPage();qp.on('pageerror',e=>errors.push(e.message));
  await qp.goto(base+'/#/appeals/'+aid);
  await qp.locator('[data-d="c1"][data-v="1"]').click();
  await qp.locator('#cm').fill('Аргумент проверен, ответ исправлен');
  const decision=qp.waitForResponse(r=>r.url().endsWith('/decide'));
  await qp.locator('#dec').click();
  assert.equal((await decision).status(),200);
  await page.reload();
  await page.locator('[data-ack]').click();
  console.log('PASS browser appeal: evidence, QA decision, revised acknowledgement');
  await qa.close();
  await page.goto(base+'/#/development');
  await page.route('**/api/development',route=>route.abort('failed'));
  await page.reload();
  await page.locator('#view > .note.bad').waitFor();
  console.log('PASS browser network error state');
  await page.unroute('**/api/development');
  const ap=await admin.newPage();
  await ap.goto(base+'/#/users');
  const uid=users.find(u=>u.role==='op'&&u.name===d.operator).id;
  const blocked=ap.waitForResponse(r=>r.url().endsWith('/api/users/'+uid)&&r.request().method()==='PATCH');
  await ap.locator('[data-act="'+uid+'"]').uncheck();
  assert.equal((await blocked).status(),200);
  assert.equal((await op.request.get(base+'/api/auth/me')).status(),401);
  console.log('PASS browser administrator: disable user and revoke session');
  await admin.close();await lead.close();await op.close();
  assert.deepEqual(errors,[]);
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
