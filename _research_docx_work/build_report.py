def p(text, bold=False, style=None):
    para = doc.add_paragraph(style=style)
    para.paragraph_format.widow_control = True
    run = para.add_run(text)
    run.bold = bold
    return para

def h(text):
    return doc.add_heading(text, level=2)

def bullet(text):
    return p(text, style='List Bullet')

def page(title):
    doc.add_page_break()
