def table(headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for c,w in zip(t.columns,widths):
        c.width = Cm(w)
    for c,txt,w in zip(t.rows[0].cells,headers,widths):
        c.width=Cm(w); c.text=txt
    repeat=OxmlElement('w:tblHeader'); t.rows[0]._tr.get_or_add_trPr().append(repeat)
    for row in rows:
        cells=t.add_row().cells
        for c,txt,w in zip(cells,row,widths):
            c.width=Cm(w); c.text=str(txt)
    borders=OxmlElement('w:tblBorders')
    for side in ['top','left','bottom','right','insideH','insideV']:
        el=OxmlElement('w:'+side); el.set(qn('w:val'),'single'); el.set(qn('w:sz'),'4'); el.set(qn('w:color'),'D9D9D9'); borders.append(el)
    t._tbl.tblPr.append(borders)
    for ri,row in enumerate(t.rows):
        trpr=row._tr.get_or_add_trPr(); no_split=OxmlElement('w:cantSplit'); trpr.append(no_split)
        for ci,c in enumerate(row.cells):
            c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
            pr=c._tc.get_or_add_tcPr()
            margins=OxmlElement('w:tcMar')
            for side in ['top','left','bottom','right']:
                el=OxmlElement('w:'+side); el.set(qn('w:w'),'85'); el.set(qn('w:type'),'dxa'); margins.append(el)
            pr.append(margins)
            sh=OxmlElement('w:shd'); sh.set(qn('w:fill'),'DFE8F0' if ri==0 else ('F5F7F9' if ri%2==0 else 'FFFFFF')); pr.append(sh)
            for para in c.paragraphs:
                para.paragraph_format.space_after=Pt(2); para.paragraph_format.line_spacing=1.02
                for run in para.runs:
                    run.font.size=Pt(9); run.bold=(ri==0)
    doc.add_paragraph().paragraph_format.space_after=Pt(1)
    return t

def link(para, label, url):
    rel=para.part.relate_to(url,RT.HYPERLINK,is_external=True)
    el=OxmlElement('w:hyperlink'); el.set(qn('r:id'),rel)
    run=OxmlElement('w:r'); pr=OxmlElement('w:rPr')
    color=OxmlElement('w:color'); color.set(qn('w:val'),'215E8C'); pr.append(color)
    run.append(pr); txt=OxmlElement('w:t'); txt.text=label; run.append(txt); el.append(run); para._p.append(el)

